"""
Charter export formatters.

Converts Charter objects into human-readable output formats:
  - Markdown (.md) — default, universal
  - JSON — machine-readable for API consumers
  - Plain text — minimal, terminal-friendly
"""

from __future__ import annotations

import json
from datetime import datetime
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from .models import Charter


def to_markdown(charter: "Charter") -> str:
    """
    Export charter as a Markdown document.

    Produces a complete, standalone .md file with:
      - YAML-like frontmatter header
      - Charter title and metadata
      - All populated sections
      - Guidance callouts
      - SPOT analysis summary
      - Next steps and conversion CTA
    """
    lines: list[str] = []
    ctx = charter.context

    # Header
    lines.append(f"# {charter.title}")
    lines.append("")
    lines.append(f"> **Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    lines.append(f"> **Organisation:** {ctx.org_name or '[Your Organisation]'}")
    lines.append(f"> **Maturity Score:** {ctx.maturity_score}% — {ctx.maturity_level}")
    lines.append(f"> **Charter Type:** {charter.charter_type.display_name}")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Executive Summary
    lines.append("## Executive Summary")
    lines.append("")
    lines.append(
        f"This charter was auto-generated from an ODGS Governance Maturity "
        f"Assessment scoring **{ctx.maturity_score}%** ({ctx.maturity_level}). "
        f"The assessment identified **{charter.metadata.get('total_gaps', 0)} gaps** "
        f"across **{charter.metadata.get('dimensions_affected', 0)} DAMA data quality "
        f"dimensions**."
    )
    lines.append("")

    # SPOT summary if available
    if ctx.spot_classifications:
        lines.append("### Root Cause Analysis (SPOT Framework)")
        lines.append("")
        icons = {
            "Standard": "📄",
            "Process": "🔄",
            "Organization": "👤",
            "Technology": "⚙️",
        }
        for category, items in ctx.spot_classifications.items():
            icon = icons.get(category, "•")
            lines.append(f"- {icon} **{category}:** {len(items)} gap(s)")
        lines.append("")

    # Affected dimensions
    if ctx.dimension_names:
        lines.append("### Key Data Quality Dimensions Affected")
        lines.append("")
        for name in ctx.dimension_names:
            lines.append(f"- {name}")
        lines.append("")

    lines.append("---")
    lines.append("")

    # Charter sections
    for section in charter.sections:
        lines.append(f"## {section.heading}")
        lines.append("")

        for paragraph in section.content:
            lines.append(paragraph)
            lines.append("")

        if section.guidance:
            lines.append(f"> 💡 **Guidance:** {section.guidance}")
            lines.append("")

        lines.append("---")
        lines.append("")

    # Cost/Risk Flags
    if ctx.cost_flags:
        lines.append("## Cost & Risk Flags")
        lines.append("")
        for flag in ctx.cost_flags:
            lines.append(f"- ⚡ {flag}")
        lines.append("")
        lines.append("---")
        lines.append("")

    # Footer / CTA
    lines.append("## Next Steps")
    lines.append("")
    lines.append(
        "This charter provides the starting framework for your "
        "governance improvement initiative. To take action:"
    )
    lines.append("")
    lines.append("1. **Validate** this charter with key stakeholders")
    lines.append("2. **Prioritise** the identified dimensions for improvement")
    lines.append("3. **Install** certified ODGS Regulation Packs to accelerate compliance")
    lines.append("4. **Re-assess** maturity after implementing improvements")
    lines.append("")
    lines.append("```")
    lines.append("# Re-run assessment after improvements:")
    lines.append("odgs-maturity score --workspace /path/to/workspace")
    lines.append("")
    lines.append("# Discover regulation packs for your gaps:")
    lines.append("odgs discover")
    lines.append("```")
    lines.append("")
    lines.append("---")
    lines.append(
        f"*Generated by [odgs-maturity](https://github.com/MetricProvenance/odgs-maturity) "
        f"v{charter.metadata.get('generator_version', '1.0.0')} — "
        f"DAMA DMBOK aligned assessment framework.*"
    )
    lines.append("")

    return "\n".join(lines)


def to_json(charter: "Charter", indent: int = 2) -> str:
    """Export charter as a JSON string."""
    return json.dumps(charter.to_dict(), indent=indent, default=str)


def to_plain_text(charter: "Charter") -> str:
    """
    Export charter as plain text (no markup).

    Suitable for terminal display or plain-text email.
    """
    lines: list[str] = []
    ctx = charter.context

    lines.append(charter.title.upper())
    lines.append("=" * len(charter.title))
    lines.append("")
    lines.append(f"Organisation: {ctx.org_name or '[Your Organisation]'}")
    lines.append(f"Maturity:     {ctx.maturity_score}% ({ctx.maturity_level})")
    lines.append(f"Generated:    {datetime.now().strftime('%Y-%m-%d')}")
    lines.append("")

    for section in charter.sections:
        lines.append(section.heading)
        lines.append("-" * len(section.heading))
        for paragraph in section.content:
            # Strip markdown bold markers
            clean = paragraph.replace("**", "").replace("*", "")
            lines.append(clean)
            lines.append("")
        lines.append("")

    return "\n".join(lines)
